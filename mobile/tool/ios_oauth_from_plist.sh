#!/bin/sh
# Generate ios/Flutter/Secrets.xcconfig from the iOS OAuth client plist
# downloaded from Google Cloud Console (client_<id>.apps.googleusercontent.com.plist).
# The output is git-ignored. Values are never printed.
set -eu

if [ $# -ne 1 ]; then
  echo "usage: $0 <client_*.plist>" >&2
  exit 2
fi
plist=$1
if [ ! -f "$plist" ]; then
  echo "not found: $plist" >&2
  exit 1
fi

client_id=$(plutil -extract CLIENT_ID raw -o - "$plist")
reversed_id=$(plutil -extract REVERSED_CLIENT_ID raw -o - "$plist")
if [ -z "$client_id" ] || [ -z "$reversed_id" ]; then
  echo "CLIENT_ID or REVERSED_CLIENT_ID is missing in $plist" >&2
  exit 1
fi

bundle_id=$(plutil -extract BUNDLE_ID raw -o - "$plist" 2>/dev/null || true)
if [ -n "$bundle_id" ] && [ "$bundle_id" != "jp.infodesk.mobile" ]; then
  echo "warning: the plist is for bundle id $bundle_id, not jp.infodesk.mobile" >&2
fi

out="$(cd "$(dirname "$0")/.." && pwd)/ios/Flutter/Secrets.xcconfig"
umask 077
cat > "$out" <<XC
// Generated by tool/ios_oauth_from_plist.sh. Do not commit.
GOOGLE_IOS_CLIENT_ID = $client_id
GOOGLE_IOS_REVERSED_CLIENT_ID = $reversed_id
XC
echo "wrote $out"
